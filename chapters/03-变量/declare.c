/*
 * 章节：变量的声明和使用
 * 知识点：
 *   变量是内存里的一块存储区，值可以在同一类型范围内改变。
 *   三要素：数据类型、变量名、存储的值。
 *   必须先声明，后使用。
 *   可以声明后再赋值，也可以声明的同时赋值。
 */
#include <stdio.h>

int main(void)
{
    int num1;          /* 只声明，此时还没有我们写入的值 */
    num1 = 10;         /* 再赋值 */

    int num2 = 20;     /* 声明同时赋值 */
    num2 = num1;       /* 用 num1 的值覆盖 num2，num1 自己不变 */

    int a = 1, b = 20, c = 30; /* 同一类型可以一次声明多个 */

    printf("num1 = %d, num2 = %d\n", num1, num2);
    printf("a = %d, b = %d, c = %d\n", a, b, c);
    return 0;
}
