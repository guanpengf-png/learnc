/*
 * 章节：C 语言里的整数进制写法
 * 知识点：
 *   进制只改变书写方式，不改变内存里的二进制存储。
 *   讲义里的二进制写法是 0b1010、0B1010。
 *   它很常见，但在严格的 C11 模式下，当前这台机器的 clang 会把它当成扩展并报警。
 *   所以下面用移位把同一个二进制值写出来：1<<3 | 1<<1 就是 1010。
 *   0        八进制（容易看错：012 不是十进制 12）
 *   普通数字 十进制
 *   0x / 0X  十六进制，A-F 不区分大小写
 *   %d 一律按十进制把值打印出来，所以 1010（二进制）和 012 都显示 10。
 */
#include <stdio.h>

int main(void)
{
    int a = (1 << 3) | (1 << 1); /* 二进制 1010 = 8+2 = 10，讲义写成 0b1010 */
    int b = 012;    /* 八进制 12 = 1*8+2 = 10 */
    int c = 101;    /* 十进制 101 */
    int d = 0x2f;   /* 十六进制 2F = 2*16+15 = 47 */

    printf("%d\n", a);
    printf("%d\n", b);
    printf("%d\n", c);
    printf("%d\n", d);

    /* 不同进制可以出现在同一个表达式里 */
    printf("混合运算 = %d\n", 10 + 015 + 0x20);
    return 0;
}
