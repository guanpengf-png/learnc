/*
 * 章节：注释
 * 知识点：
 *   注释不会被编译，不产生指令。
 *   作用 1：解释这段代码为什么这样写。
 *   作用 2：临时关掉一段还不想执行的代码。
 *   两个斜杠     单行注释，到行尾结束
 *   斜杠星号     块注释，可以跨行。块注释不能嵌套。
 */
#include <stdio.h>

int main(void)
{
    // 这是单行注释：编译器会丢掉这一整行说明
    printf("这行会执行\n");

    /*
     * 这是多行注释。
     * 下面这句被注释掉了，所以不会打印。
     * printf("这行不会执行\n");
     */

    printf("注释本身不会出现在输出里\n");
    return 0;
}
