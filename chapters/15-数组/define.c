/*
 * 章节：数组的定义
 * 知识点：
 *   数组是同一类型的一组数据，按顺序排在一起，用一个名字管理，用下标访问。
 *   下标从 0 开始，连续递增。元素个数叫长度。
 *   创建时要一整块连续内存。长度在定义完成后就固定，不能再改。
 *   三种定义：
 *     int a[3];                   先定长度。局部数组不赋值，里面是垃圾值，读之前必须赋值。
 *     int b[3] = {100, 200, 300}; 定长度，同时初始化。
 *     int c[] = {1, 2, 3, 4, 5};  不写长度，编译器按花括号里的个数计算。
 *   C99 可变长数组：长度可以用变量，但必须等程序跑起来才知道。
 *     这种数组不能写花括号初始化：int v[n] = {10, 20, 30}; 是错的。
 *   数组直接量（复合字面量）：(int[3]){10, 20, 30}。它是临时数组，这条语句结束就没了。
 */
#include <stdio.h>

int main(void)
{
    int arr1[3];
    arr1[0] = 10;
    arr1[1] = 20;
    arr1[2] = 30;
    printf("先定义再赋值: %d %d %d\n", arr1[0], arr1[1], arr1[2]);

    int arr2[3] = {100, 200, 300};
    printf("定义时初始化: %d %d %d\n", arr2[0], arr2[1], arr2[2]);

    int arr3[] = {1, 2, 3, 4, 5};
    printf("省略长度，元素个数 = %zu\n", sizeof arr3 / sizeof arr3[0]);

    int len = 3;
    int arr4[len];
    for (int i = 0; i < len; i++) {
        arr4[i] = (i + 1) * 10;
    }
    printf("可变长数组: %d %d %d\n", arr4[0], arr4[1], arr4[2]);

    printf("数组直接量: ");
    for (int i = 0; i < 3; i++) {
        printf("%d ", (int[3]){10, 20, 30}[i]);
    }
    printf("\n");
    return 0;
}
