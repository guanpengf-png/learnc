/*
 * 章节：断点调试
 * 知识点：
 *   结果不对、又看不出哪一行错时，用调试器让程序停在某一行。
 *   在行号左侧点击，或把光标放在那一行按 F9，设置断点。
 *   F5 开始调试，程序会停在第一个断点。
 *   F10 逐过程：执行当前这一行，不进入函数内部。
 *   F5 继续：直接跑到下一个断点。
 *   停下时看变量窗口，或把鼠标放在 sum、i 上。
 *
 * 建议把断点打在 sum += i 这一行，然后连续按 F10，
 * 观察 i 从 0 增加到 9 时，sum 如何变成 0、1、3、6、10……
 */
#include <stdio.h>

int main(void)
{
    int sum = 0;
    for (int i = 0; i < 10; i++) {
        sum += i;
        printf("i = %d, sum = %d\n", i, sum);
    }
    return 0;
}
