/*
 * 章节：块级作用域
 * 知识点：
 *   C99 起，一对花括号里声明的变量只在这对花括号里有效。for 圆括号里声明的循环变量也一样。
 *   块结束，里面的变量就销毁。出了块再使用，会编译失败。
 *   块级变量和函数里的局部变量一样：不初始化就是垃圾值，存在栈上。
 */
#include <stdio.h>

int main(void)
{
    {
        int a = 10;
        double d = 10.23;
        printf("a = %d, d = %f\n", a, d);
    }
    /* 这里已经不能再写 a 和 d。 */

    for (int i = 0; i < 3; i++) {
        printf("%d,", i);
    }
    printf("\n");
    /* 这里也不能再写 i。 */
    return 0;
}
