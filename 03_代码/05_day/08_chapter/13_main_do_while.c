#include <stdio.h>
int main()
{
  // do-while循环
  /*

    do-while循环语法:

    do{
      循环体语句
    }while(条件表达式);
    =================================
    int i=0; 计数器
     do{
      循环体语句;
      i++;
    }while(i<3);


    do-while循环执行过程:代码从上到下执行,int i=0;计数器这一行代码就执行一次,执行大括号中的循环体语句,之后计数器累加的代码执行i++,判断条件表达式i<3是否成立(真---1---true/假----0---false)如果为假,则循环结束,如果为真,则继续执行大括号中的代码,然后执行i++,再判断i<3是否成立,如果为假则循环结束,否则继续执行大括号中的代码,直到条件表达式为假,循环结束为止



  */
  // 例子:输出第几天吃了几个包子
  int i = 0;
  do{
    printf("第%d天吃了%d个包子\n",i+1,i+1);
    i++;
  } while (i < 10);
  printf("最终i的值是:%d\n",i);

  return 0;
}