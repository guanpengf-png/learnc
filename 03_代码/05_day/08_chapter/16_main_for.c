#include <stdio.h>
int main()
{
  // for循环
  /*

    for循环的语法:

      for(表达式1;表达式2;表达式3){
        循环体语句代码;
      }

      for(int i=0;i<3;i++){
        循环体语句代码;
      }

    for循环的执行过程:先执行for()里面的第一个表达式(就执行一次),执行第二个表达式(i<3)判断是否成立(真---1---true/假---0---false)
    如果不成立,for循环结束,如果成立,则执行循环体语句代码,然后再执行表达式3,然后再判断表达式2是否成立,如果不成立循环就结束,成立则继续执行循环体语句代码,...

    for循环的简化写法:如果循环体语句只有一行,大括号也可以省略,要注意缩进




  */
  // 例子:显示第几天吃几个包子
  for (int i = 0; i < 10; i++)
    printf("第%d天吃了%d个包子\n", i + 1, i + 1);

  // printf("最终i的值是:%d\n",i);

  return 0;
}