#include <stdio.h>

int get_sum(int x,int y){
  return x + y;
}
int main()
{
  get_sum(10,20);
  get_sum((int)12.34,(int)23.45);
  // 函数参数的理解:
  /*
    函数声明或定义的语法:
    返回值类型 函数名([参数列表]){函数体语句代码;}
    函数调用语法:
    函数名([参数列表]);

    函数在声明的时候函数名字后面小括号中的变量声明就是参数
    函数在调用的时候函数名字后面小括号中的数据就是参数

    无论是函数声明还是函数调用,小括号中的数据都是参数

    void f1(int x){}
    f1(10);
    int a=10;
    f1(a);

    形参(形式参数):函数声明的时候函数名字后面小括号中的变量声明就叫形参
    实参(实际参数):函数调用的时候函数名字后面小括号中传入的数据就叫实参
    函数调用的时候传入的实参的数量和类型应该和函数声明的时候形参的数量及类型应该保持一致

  */

  return 0;
}