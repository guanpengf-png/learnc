#include <stdio.h>
int main()
{
  // 字符数组:就是一个数组,里面存储了很多的字符,字符数组可以看成是字符串
  // 字符:单个的字母/数字/符号使用一对单引号括起来,就是字符类型的数据值,也可以叫字符值
  // 字符串:由单个或多个的字符使用一对双引号括起来,就是字符串数据值,简称字符串
  // 字符的占位符是%c,字符串的格式占位符是%s,字符串是需要有结束符的,\0---空字符---看不到,不占位,且真实存在的

  // 字符数组的声明或定义:

  // 方式1: 语法:数据类型名 数组名[长度] = {};
  // 1. 设定长度的同时,直接赋值,且结尾处有\0表示结束
  char chs1[5] = {'a', 'b', 'c', 'd', '\0'};
  printf("chs1=%s\n", chs1);
  // 2. 设定长度的同时,直接赋值,结尾处没有\0,自动添加\0表示结束
  char chs2[5] = {'a', 'b', 'c', 'd'};
  printf("chs2=%s\n", chs2);
  // 3. 没有设定长度,同时赋值,手动在结尾处增加\0表示结束
  char chs3[] = {'a', 'b', 'c', 'd', 'e', '\0'};
  printf("chs3=%s\n", chs3);
  // 4. 设定长度的同时直接赋值,结尾处没有\0,数据的个数和长度一样
  char chs4[5] = {'a', 'b', 'c', 'd', 'e'};
  printf("chs4=%s\n",chs4);
  // 5. 没有设定长度,也没有\0表示结束
  char chs5[] = {'a','b','c'};
  printf("chs5=%s\n",chs5);
  // 6. 没有设定长度,赋值的时候大括号中以字符串的形式进行赋值
  char chs6[] = {"abcde"};
  printf("chs6=%s\n",chs6);
  // 7. 没有设定长度,直接以双引号的方式进行赋值
  char chs7[] = "hello";
  printf("chs7=%s\n",chs7);

  return 0;
}