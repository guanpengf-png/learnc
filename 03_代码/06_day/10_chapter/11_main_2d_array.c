#include <stdio.h>
int main()
{
  // 一维数组:就是数组,声明的时候使用一个[],赋值的时候里面的数据是基本类型的数据值
  // 二维数组:就是数组,里面的数组元素是数组(一维数组)
  // 多维数组:就是数组,声明的时候使用多个[],赋值的时候里面的数据是数组,二维及二维以上的数组都可以看成是多维数组
  // 线性结构:线性关系,数据和数据之间的关系,称为结构,一维数组,二维数组都属于线性结构

  // 二维数组声明或定义的方式

  // 方式1:先声明后赋值,语法:数据类型名 数组名[行索引][列索引];
  // 声明了一个二维数组,起名为nums1,类型是:int[2][3],表示:两行三列的二维数组
  int nums1[2][3];
  nums1[0][0] = 10; // 第一行的第一列
  nums1[0][1] = 20; // 第一行的第二列
  nums1[0][2] = 30; // 第一行的第三列
  nums1[1][0] = 40; // 第二行的第一列
  nums1[1][1] = 50; // 第二行的第二列
  nums1[1][2] = 60; // 第二行的第三列
  // 方式2:声明的同时直接赋值,里面的元素是数组
  int nums2[2][3] = {
    {10,20,30},
    {40,50,60}
  };
  // 方式3:声明的同时直接赋值,以单个数据进行赋值
  int nums3[2][3] = {10,20,30,40,50,60};
  // 方式4:声明的同时直接赋值,省略行索引,设定列索引
  int nums4[][3] = {10,20,30,40,50,60,70,80,90};
  // int nums5[3][] = {10,20,30,40,50,60,70,80,90};

  return 0;
}