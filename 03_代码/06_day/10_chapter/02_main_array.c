#include <stdio.h>
int main()
{
  // 数组的声明或定义的方式:
  // 1.可以先声明后赋值
  // 2.可以声明的同时直接赋值

  // 1. 先声明后赋值的语法:
  // 数据类型名 数组名[长度];
  // 赋值的语法: 数组名[索引] = 值;
  // 读取值/获取值的语法:数组名[索引]
  int nums[3]; // 声明了一个长度为3的数组(可以存储3个数据),起名为nums,类型是:int[3]
  nums[0] = 10;
  nums[1] = 20;
  nums[2] = 30;
  printf("索引:0位置的数据是:%d\n", nums[0]);
  printf("索引:1位置的数据是:%d\n", nums[1]);
  printf("索引:2位置的数据是:%d\n", nums[2]);
  printf("\n============\n");
  // 2. 声明的同时直接赋值的语法:
  // 数据类型名 数组名 [长度]={元素1,元素2,元素3};
  int arr[3] = {100, 200, 300};
  printf("索引:0位置的数据是:%d\n", arr[0]);
  printf("索引:1位置的数据是:%d\n", arr[1]);
  printf("索引:2位置的数据是:%d\n", arr[2]);
  printf("\n============\n");
 printf("索引:0位置的数据是:%d=====内存地址:%p\n", arr[0],&arr[0]);
 printf("索引:1位置的数据是:%d=====内存地址:%p\n", arr[1],&arr[1]);
 printf("索引:2位置的数据是:%d=====内存地址:%p\n", arr[2],&arr[2]);

 // 3. 声明的同时直接赋值,不设定长度
  int nums[] = {10,20,30,40,50};
  // int num = 10; // num的类型是:int

  // int num1 = 10;
  // int num2 = 20;
  // printf("num1变量的地址是:%p\n",&num1);
  // printf("num2变量的地址是:%p\n",&num2);

  return 0;
}