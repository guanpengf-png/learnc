#include <stdio.h>
// 结构体类型:属于自定义数据类型中的一种,这种类型的变量,可以看成是一个容器,特点:可以一次性存储多个不同类型的数据


// 数组:是一个容器,可以存储多个相同类型的数据
// 结构体:也可以看成是一个容器,可以存储多个不同类型的数据
/*
  结构体类型定义语法:

  struct 结构体类型名{
    数据类型名 变量名;
    数据类型名 变量名;
    数据类型名 变量名;
    ...
  };
  结构体类型名:符合标识符的命名规范,一般使用大驼峰命名法
   数据类型名 变量名; 成员类型 成员名; 数据类型名 属性名;---------------就是变量的声明
   结构体类型定义的位置:可以在函数外部,也可以在函数内部

*/
// 定义一个关于人的结构体类型
struct Person{
  char *name; // 名字
  char gender; // 性别
  int age; // 年龄
};
// 定义一个关于学生的结构体类型
struct Student{
  int id; // 学号
  char *name; // 名字
  char gender; // 性别
  int age; // 年龄
  int math_score; // 数学成绩
};

