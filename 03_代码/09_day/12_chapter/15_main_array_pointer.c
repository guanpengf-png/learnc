#include <stdio.h>
int main()
{
  // 数组指针:就是指针变量,指向的是数组的内存地址
  // 数组指针的声明或定义的语法:
  // 1. 先声明后赋值
  // 2. 声明的同时直接赋值

  // 1.数组指针先声明后赋值语法:
  // 数据类型 (*数组指针名)[长度];
  // 赋值的语法: 数组指针名 = &数组名;
  int nums[] = {10,20,30};
  int(*arr_ptr)[3]; // 声明了一个数组指针,起名为arr_ptr,类型是: int(*)[3]
  arr_ptr = &nums;

  // 2. 数组指针声明的同时直接赋值语法:
  // 数据类型名 (*数组指针名)[长度] = &数组名;
  int(*arr_ptr)[3] = &nums;

  return 0;
}