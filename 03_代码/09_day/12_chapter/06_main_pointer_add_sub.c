#include <stdio.h>
int main()
{
  //  1.指针变量可以加/减一个整数
  // 指针变量加一个整数:自身指向不变
  // 指针变量减一个整数:自身指向不变
  // 指针变量加一个整数的结果:表示向后移动多少个单位(数字*数据所占的字节数的结果)
  // 例如:指针变量ptr+n,表示:ptr指针的指向向后移动了n个单位
  // 指针变量ptr默认指向的是整数的内存地址,n如果为3,ptr+n:含义就是ptr+(3*4),向后移动3个单位,也可以说向后移动12个字节,ptr自身的指向不变

   // 指针变量减一个整数的结果:表示向前移动多少个单位(数字*数据所占的字节数的结果)
  // 例如:指针变量ptr-n,表示:ptr指针的指向向前移动了n个单位
  // 指针变量ptr默认指向的是整数的内存地址,n如果为3,ptr-n:含义就是ptr-(3*4),向前移动3个单位,也可以说向前移动12个字节,ptr自身的指向不变

  int nums[] = {10, 20, 30, 40, 50};
  // 声明一个int*类型的指针变量,起名为ptr,指向的是数组中第一个元素的内存地址
  int *ptr = &nums[0];
  int len = sizeof(nums) / sizeof(int); // 长度
  for (int i = 0; i < len; i++)
    printf("索引:%d,元素值:%d,内存地址:%p\n", i, nums[i], &nums[i]);
  printf("\n=====================\n");
  printf("ptr指针变量指向的内存地址:%p,及对应内存空间中的数据:%d\n", ptr, *ptr);
  // ptr + 1; // 指针变量可以加一个整数,自身的值不变,指向没有改变
  // printf("ptr指针变量指向的内存地址:%p,及对应内存空间中的数据:%d\n", ptr, *ptr);
  printf("\n=====================\n");
  // 指针变量加一个整数
  printf("ptr指针变量指向的内存地址:%p,及对应内存空间中的数据:%d\n", ptr + 1, *(ptr + 1));
  printf("\n=====================\n");
  ptr = &nums[4]; // ptr指向改变了,指向的是数组中50的内存地址
  printf("ptr指针变量指向的内存地址:%p,及对应内存空间中的数据:%d\n", ptr - 2, *(ptr - 2));
  ptr = &nums[0]; // ptr指向改变了,指向的数中第一个元素10的内存地址
  // 改变指向的结果
  printf("ptr指针变量指向的内存地址:%p,及对应内存空间中的数据:%d\n", ptr + 3, *(ptr + 3));
  // 自身的结果
  printf("ptr指针变量指向的内存地址:%p,及对应内存空间中的数据:%d\n", ptr, *ptr);

  return 0;
}
