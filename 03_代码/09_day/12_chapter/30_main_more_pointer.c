#include <stdio.h>
int main()
{
  /*
    一级指针:该指针声明的时候用一个*,指向的是普通变量的内存地址
    二级指针:该指针声明的时候用两个*,指向的是一级指针的内存地址
    三级指针:该指针声明的时候用三个*,指向的是二级指针的内存地址
    多级指针:超一级指针的指针都可以叫多级指针(二级指针及二级指针以上的指针)


  */
  int num = 10;
  int *ptr1 = &num;                                           // ptr1是一级指针
  int **ptr2 = &ptr1;                                         // ptr2是二级指针
  int ***ptr3 = &ptr2;                                        // ptr3是三级指针
  printf("num变量的值:%d,num变量的内存地址:%p\n", num, &num); // 10
  printf("\n===========\n");
  printf("ptr1一级指针变量指向的内存地址对应的内存空间中的数据是:%d\n", *ptr1); // 10
  printf("ptr1一级指针变量指向的内存地址:%p\n", ptr1);
  printf("ptr1一级指针变量自己的内存地址:%p\n", &ptr1);
  printf("\n===========\n");
  printf("ptr2二级指针指向的一级指针变量所指向的内存地址对应的内存空间中的数据值是:%d\n", **ptr2);
  printf("ptr2二级指针指向的一级指针变量所指向的内存地址:%p\n", *ptr2);
  printf("ptr2二级指针变量指向的一级指针的内存地址:%p\n", ptr2);
  printf("ptr2二级指针变量自己的内存地址:%p\n", &ptr2);
  printf("\n===========\n");
  printf("ptr3三级指针变量指向的二级指针变量所指向的一级指针变量所指向的内存地址对应的内存空间中的数据是:%d\n", ***ptr3);
  printf("ptr3三级指针变量指向的二级指针变量所指向的一级指针变量所指向的内存地址:%p\n", **ptr3);
  printf("ptr3三级指着变量指向的二级指针变量所指向的内存地址:%p\n", *ptr3);
  printf("ptr3三级指针变量指向的二级制指针的内存地址:%p\n", ptr3);
  printf("ptr3三级指针变量自己的内存地址:%p\n", &ptr3);

  return 0;
}