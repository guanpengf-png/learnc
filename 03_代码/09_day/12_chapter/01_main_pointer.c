#include <stdio.h>
int main()
{
  // 内存:指的是内存空间,由一个一个的内存存储单元组成,每个内存存储单元就是一个字节,都有对应的编号,这个编号就是内存地址.
  // int num = 10; // num是变量,对应的数据类型是int,10是整型数据值,占4个字节

  // 指针:就是指针变量,该变量中存储的是内存地址,指针变量也是一个容器
  // 指针的作用/指针变量的作用:多了一种访问/修改/设置数据的方式
  // 访问内存空间中的数据方式:两种,方式1:直接通过变量名访问---直接访问,方式2:通过指针解引用访问----间接访问
  






  int num = 10; // 声明了一个变量,起名为num,类型是int,赋值为10,num变量的类型是:int
  int *ptr = &num; // 声明了一个指针变量,起名为ptr,类型是:int *, 赋值为num变量的内存地址,ptr指针变量的类型是int *
  

  printf("num变量的值是:%d,num变量对应的内存地址是:%p\n",num,&num);
  printf("ptr指针变量指向内存地址对应的内存空间中的数据值是:%d\n",*ptr);
  printf("ptr指针变量指向的内存地址:%p\n",ptr);
  printf("ptr指针变量自己的内存地址:%p\n",&ptr);

  // num = 100; // 修改变量的值
  *ptr = 1000; // 通过解引用指针变量的方式来修改变量中的数据值

  printf("num变量的值是:%d,num变量对应的内存地址是:%p\n", num, &num);
  printf("ptr指针变量指向内存地址对应的内存空间中的数据值是:%d\n",*ptr);
  printf("ptr指针变量指向的内存地址:%p\n",ptr);
  printf("ptr指针变量自己的内存地址:%p\n",&ptr);
  printf("num变量对应的内存地址所占的字节数:%zu\n",sizeof(&num)); // 8

  // &-----取地址符------取址符
  // *-----间接引用符----取值符------解引用
  // %p----格式占位符----用来显示内存地址的
  // &变量名-----该变量对应的内存地址
  // *指针变量名----解引用,目的是:找到该指针变量指向的内存地址(变量的内存地址)对应的内存空间中的数据值
  return 0;
}