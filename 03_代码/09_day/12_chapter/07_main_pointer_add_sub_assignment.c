#include <stdio.h>
int main()
{
  // 2.指针变量可以加等于/减等于一个整数,加等于(相加赋值+=),减等于(相减赋值-=)
  // 无论是指针变量相加赋值或相减赋值 或者 加减整数重新赋值 能表示自身指向改变,也可以表示可以向后或向前移动
  // 指针变量相加赋值或相减赋值可以进行运算,同时自身指向可以改变
  // 指针变量加减整数重新赋值也可以进行运算,同时自身指向可改变
  int nums[] = {10, 20, 30, 40, 50};
  // 声明一个int*类型的指针变量,起名为ptr,指向的是数组中第一个元素的内存地址
  int *ptr = &nums[0];
  int len = sizeof(nums) / sizeof(int); // 长度
  for (int i = 0; i < len; i++)
    printf("索引:%d,元素值:%d,内存地址:%p\n", i, nums[i], &nums[i]);
  printf("\n=====================\n");
  printf("ptr指针变量指向的内存地址:%p,及对应内存空间中的数据:%d\n", ptr, *ptr);
  // ptr += 3; // 指针变量可以进行加等于运算
  ptr = ptr + 3; // 向后移动3个单位(12个字节)
  printf("ptr指针变量指向的内存地址:%p,及对应内存空间中的数据:%d\n", ptr, *ptr);
  // ptr -= 2; // 指针变量可以进行减等于运算
  ptr = ptr - 2; // 向前移动2个单位(8个字节)
  printf("ptr指针变量指向的内存地址:%p,及对应内存空间中的数据:%d\n", ptr, *ptr);

  return 0;
}