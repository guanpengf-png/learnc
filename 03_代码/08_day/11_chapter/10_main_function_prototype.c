#include <stdio.h>
/*
函数原型是一个工具,能够解决函数调用的时候可能会出现的警告或纰漏
函数的定义也可以叫函数原型
函数定义:返回值类型 函数名([参数列表]){函数体语句代码}
函数的声明或定义的代码可以拆分为函数头和函数体
函数头: 返回值类型名 函数名([参数列表])
函数体: {函数体语句代码;}
函数头的代码可以叫函数原型声明
只有函数头的代码加分号-----函数声明
函数头+函数体的整体代码----函数定义
void f1()
{
  函数体语句代码
}
函数头;就是函数原型声明
void f2(int x); ----函数头----函数原型声明
简化:
void f2(int); ----函数头----函数原型声明

函数原型的作用:解决先调用,后定义,编译器出现的警告信息的问题

函数原型是一种原型语法,包括函数声明或函数定义

函数原型声明的语法书写方式有三种:

1. 返回值类型 函数名([参数列表]);

2. 返回值类型 函数名([参数列表]){函数体语句代码;}

3. 返回值类型 函数名(int x,...);
   返回值类型 函数名(int x,...){函数体语句代码;}


*/
