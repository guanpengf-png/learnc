#include <stdio.h>
// 变量/常量/数组,在访问和使用的时候有个就近原则
// 变量/常量/数组在使用的时候优先找当前作用域声明的位置获取数据值,如果当前作用域中没有变量/常量/数组.就去上一级作用域中找,找到则使用,找不到则继续向上一级作用域查找,找到则使用,找不到则继续向上一级查找,直到找到全局作用域中,如果还没有,则报错
int num = 10; // 全局变量
int main()
{
  int num = 20; // 局部变量
 
  {
    int num = 30; // 块级变量
    printf("num=%d\n",num);
  }

  return 0;
}