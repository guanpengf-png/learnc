#include <stdio.h>
//
/*

函数的声明或定义的语法:

  返回值类型名 函数名([参数列表]){
    函数体语句;/函数体代码;
  }

  函数调用的语法:
  函数名([参数列表]);

  返回值类型名:就是数据类型名/void---空类型---无类型
  函数名:符合标识符的命名规范:使用小驼峰命名法或下划线连接多个单词,都是小写,最好有意义
  [参数列表]:可有可无,就是一个或多个变量的声明的写法,如果没有,小括号啥也不写
  {函数体语句;}:可以是一行代码也可以是多行代码,表达的是具体功能的实现
  函数声明或定义的位置:在main主函数的外部

  函数的四个要素:返回值类型名,函数名,参数列表,函数体语句
  函数要想使用:必须先声明或定义,后调用



*/
// 需求:调用函数可以输出一句打招呼的内容
// 声明或定义一个函数
void say_hi(){
  printf("啊捏哈涩呦\n");
}
// 需求:计算两个数字的和通过函数实现
int get_sum(int num1,int num2){
  return num1 + num2;
}
// 需求:计算两个整数的最大值,通过函数实现
int get_max_number(int x,int y){
  return x > y ? x : y;
}
int main()
{
  say_hi(); // 调用函数(使用函数)
 int sum= get_sum(100, 200); // 调用函数
 printf("和为:%d\n",sum); // 输出结果
 int a = 10, b = 20;
 int max_num= get_max_number(a, b); // 调用函数,并传入参数
 printf("最大值是:%d\n",max_num);
 return 0;
}