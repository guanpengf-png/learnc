#include <stdio.h>
int main()
{
  // 指针数组:就是数组,里面存储的每个元素是指针(指针变量/变量的内存地址/内存地址)
  // 指针数组的声明或定义方式:先声明后赋值或者声明的同时直接赋值
  // 1. 先声明后赋值的语法:
  // 数据类型名 * 指针数组名[长度];
  // 赋值语法: 指针数组名[索引]= 值;
  int a = 10, b = 20, c = 30;
  int *ptr_arr[3]; // 声明了一个长度为3的指针数组,起名为ptr_arr,类型是: int *[3]
  ptr_arr[0] = &a;
  ptr_arr[1] = &b;
  ptr_arr[2] = &c;

  // 2. 声明的同时直接赋值的语法:
  // 数据类型名* 指针数组名[长度]={指针变量1,指针变量2,指针变量3};
  // 数据类型名* 指针数组名[长度]={&变量1,&变量2,&变量3};
  int *ptr_arr2[3] = {&a, &b, &c}; // 指针数组
  int *ptr1 = &a;
  int *ptr2 = &b;
  int *ptr3 = &c;
  int *ptr_arr3[] = {ptr1, ptr2, ptr3}; // 指针数组

  return 0;
}